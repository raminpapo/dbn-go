def create_global_keywords():
    """Aggregate all keywords from *_kw.md files"""
    keywords = defaultdict(list)

    for kw_file in DOCS_ROOT.rglob("*_kw.md"):
        rel_path = kw_file.relative_to(DOCS_ROOT)
        parent_path = str(rel_path.parent)
        if parent_path == '.':
            parent_path = ''

        # Read keywords from file
        with open(kw_file, 'r', encoding='utf-8') as f:
            content = f.read()

        # Extract keyword sections
        for match in re.finditer(r'### ([^\n]+)\n\n- \*\*Description\*\*: ([^\n]+)', content):
            keyword, description = match.groups()
            keywords[keyword].append((description, str(rel_path)))

    # Write global keywords file
    kw_content = """# Global Keyword Index

This file contains an alphabetical index of all keywords, identifiers, types, functions, and concepts found across the dbn-go repository.

## Index

"""

    for keyword in sorted(keywords.keys(), key=str.lower):
        kw_content += f"- [{keyword}](#{keyword.lower().replace(' ', '-')})\n"

    kw_content += "\n## Keywords\n\n"

    for keyword in sorted(keywords.keys(), key=str.lower):
        kw_content += f"### {keyword}\n\n"
        for desc, file_path in keywords[keyword]:
            kw_content += f"- {desc} - [`{file_path}`](./{file_path})\n"
        kw_content += "\n"

    kw_content += """
---
*Generated by repo-book-generator*
"""

    with open(DOCS_ROOT / "keywords.md", 'w', encoding='utf-8') as f:
        f.write(kw_content)

    return len(keywords)

